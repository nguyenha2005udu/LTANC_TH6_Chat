import { updateProfile } from 'firebase/auth';
import { ref, set } from 'firebase/database';
import { auth, database } from './firebase';
import { uploadImage, type PickedImage } from './uploadService';

function currentUser() {
  const user = auth.currentUser;
  if (!user) {
    throw new Error('Bạn cần đăng nhập trước.');
  }
  return user;
}

/** users/{uid}/name is what Contacts, Home, chats and notifications show. */
export async function updateName(name: string) {
  const clean = name.trim();
  if (!clean || clean.length > 100) {
    throw new Error('Họ tên cần từ 1 đến 100 ký tự.');
  }
  const user = currentUser();
  await Promise.all([
    set(ref(database, `users/${user.uid}/name`), clean),
    updateProfile(user, { displayName: clean }),
  ]);
}

/** Uploads the photo to Cloudinary and stores only its URL in users/{uid}/avatar. */
export async function updateAvatar(image: PickedImage) {
  const user = currentUser();
  const url = await uploadImage(image);
  await set(ref(database, `users/${user.uid}/avatar`), url);
  return url;
}

/** Square, face-centred thumbnail generated by Cloudinary on the fly. */
export function avatarThumb(url: string, size = 160) {
  return url.includes('/image/upload/')
    ? url.replace(
        '/image/upload/',
        `/image/upload/c_fill,g_face,w_${size},h_${size},q_auto/`,
      )
    : url;
}
